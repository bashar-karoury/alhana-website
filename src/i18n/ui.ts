export type UIKey = keyof (typeof strings)['en'];

export const useT = (lang: Lang) => (key: UIKey) => strings[lang][key];

/** "8 series" / "8 سلاسل" with Arabic dual/singular forms. */
export const seriesCount = (lang: Lang, n: number) => {
  const t = useT(lang);
  if (n === 1) return t('cats.oneSeries');
  if (n === 2) return t('cats.twoSeries');
  return `${n} ${t('cats.series')}`;
};
